// Actual Chromium + physical Python HTTP server + PostgreSQL, no mocked routes.
import { chromium, expect } from '@playwright/test';
import { readFileSync } from 'node:fs';
import { createInterface } from 'node:readline';
import assert from 'node:assert/strict';
const config = JSON.parse(readFileSync(process.env.PANESTRIA_BROWSER_FIXTURE,'utf8'));
const input = createInterface({input:process.stdin})[Symbol.asyncIterator]();
async function step(name) {console.log(name); const next = await input.next(); assert(!next.done); return JSON.parse(next.value);}
const browser = await chromium.launch({headless:true});
try {
  const context = await browser.newContext();
  await context.addCookies([{name:'panestria_session',value:'legacy-owner-cookie-sentinel',url:config.origin}]);
  const page = await context.newPage(); const errors=[]; page.on('pageerror',e=>errors.push(e.message));
  const requests=[]; page.on('request',r=>requests.push(r.url()));
  await page.goto(config.origin);
  await expect(page.getByRole('heading',{name:'Mission Control',exact:true})).toBeVisible();
  await page.getByLabel('One-use pairing code from your terminal').fill(config.code);
  await page.getByRole('button',{name:'Pair',exact:true}).click();
  await page.getByRole('button',{name:`Open goal ${config.goal.slice(0,8)}`,exact:true}).click();
  await expect(page.getByTestId('goal-state')).toHaveText('ACTIVE');
  await expect(page.locator('[data-event-id]')).toHaveCount(55);
  await expect(page.getByTestId('cursor')).toHaveText('9007199254741047');
  const cookies = await context.cookies();
  assert(cookies.some(c=>c.name==='panestria_session' && c.value==='legacy-owner-cookie-sentinel'));
  const session = cookies.find(c=>c.name.startsWith('panestria_mission_'));
  assert(session?.httpOnly && session.sameSite==='Strict');
  assert.equal(await page.evaluate(()=>localStorage.length+sessionStorage.length),0);
  assert(!await page.evaluate(()=>document.cookie.includes('panestria_mission_')));
  await context.setOffline(true);
  await expect(page.getByRole('region',{name:'Goal timeline'})).toContainText('STALE / UNCONFIRMED',{timeout:25000});
  await step('OFFLINE');
  await context.setOffline(false);
  await expect(page.locator('[data-event-id]')).toHaveCount(57,{timeout:25000});
  await expect(page.getByTestId('goal-state')).toHaveText('ACTIVE');
  await expect(page.getByRole('region',{name:'Goal timeline'})).toContainText('RECONCILING');
  const ids = await page.locator('[data-event-id]').evaluateAll(nodes=>nodes.map(n=>n.dataset.eventId));
  assert.equal(new Set(ids).size,57);
  await page.screenshot({path:process.env.PANESTRIA_BROWSER_SCREENSHOT,fullPage:true});
  await step('RETIRE');
  await expect(page.locator('[data-event-id]')).toHaveCount(0,{timeout:25000});
  await expect(page.getByTestId('goal-state')).toHaveText('ACTIVE');
  await step('REVOKE');
  await expect(page.getByRole('region',{name:'Project activity'})).toHaveCount(0,{timeout:25000});
  await expect(page.getByRole('region',{name:'Goal timeline'})).toHaveCount(0);
  const paired = await step('REPAIR');
  await page.getByLabel('One-use pairing code from your terminal').fill(paired.code);
  await page.getByRole('button',{name:'Pair',exact:true}).click();
  await expect(page.getByRole('region',{name:'Project activity'})).toBeVisible();
  await page.getByRole('button',{name:'Log out',exact:true}).click();
  await expect(page.getByText('Session revoked.',{exact:true})).toBeVisible();
  assert((await context.cookies()).some(c=>c.name==='panestria_session' && c.value==='legacy-owner-cookie-sentinel'));
  assert(!(await context.cookies()).some(c=>c.name.startsWith('panestria_mission_')));
  assert.equal((await context.request.get(config.origin+'/v1/activity')).status(),401);
  assert.equal(await page.evaluate(()=>localStorage.length+sessionStorage.length),0);
  assert(!requests.some(url=>/[?&](token|csrf|session|code)=/.test(url)));
  assert(!await page.content().then(s=>s.includes('PRIVATE_MISSION_SENTINEL')));
  assert.deepEqual(errors,[]);
  console.log('PASS');
} finally {await browser.close();}
